// Ab hier: aus den Zeilen werden Objekte gebaut.
function parsePortions(spec, liquid) {
  const unit = liquid ? "ml" : "g";
  return String(spec || "100").split(";").map(part => {
    const [label, grams] = part.includes("=") ? part.split("=") : [null, part];
    const g = Number(grams) || 100;
    return {g, label: label ? `${label.trim()} (${g} ${unit})` : `${g} ${unit}`, short: label ? label.trim() : `${g} ${unit}`};
  });
}

function buildFood(row) {
  const [n, group, k100, p100, co2, spec, rawFlags, tags, alt] = row;
  let flags = String(rawFlags || "");
  if (group === "milch" && !flags.includes("M")) flags += "M";
  if (group === "ei" && !flags.includes("E")) flags += "E";
  if (group === "fisch" && !flags.includes("F") && !flags.includes("K")) flags += "F";
  if (group === "fleisch" && !flags.includes("T")) flags += "T";
  const liquid = group === "getraenk" || flags.includes("l");
  const portions = parsePortions(spec, liquid);
  return {
    n, group, k100, p100, co2, flags, liquid, portions,
    g: portions[0].g,
    u: portions[0].label,
    tags: tags || "",
    alt: alt || (group === "fleisch" ? "protein" : group === "fisch" ? "fisch" : ""),
    src: "liste"
  };
}

const FOODS = FOOD_ROWS.map(buildFood);
